/* ============================================================
   어두운 방의 배치.

   좌표는 **화면 비율(0~1)** 로 적는다. 픽셀로 적으면 창 크기가
   바뀔 때마다 물건이 화면 밖으로 나간다.
   ============================================================ */

/** 찾아야 하는 것. 0.4초 비추면 발견된다. */
export type Secret = {
  id: string
  /** 중심 위치 (화면 비율) */
  x: number
  y: number
  /** 위에 크게 뜨는 글 */
  line: string
  /** 아래 작게 뜨는 글 */
  sub?: string
  /** 글 상자를 어느 쪽으로 벌릴지 — 화면 밖으로 나가지 않게 */
  align?: 'left' | 'center' | 'right'
}

/** 빛을 막는 물건. 뒤로 그림자가 뻗는다. */
export type Prop = {
  x: number       // 중심
  y: number
  w: number       // 폭 (화면 비율, 가로 기준)
  h: number       // 높이 (화면 비율, 세로 기준)
  /** 살짝 기울이면 방이 버려진 곳처럼 보인다 */
  tilt?: number   // deg
}

